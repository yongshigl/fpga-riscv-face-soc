#!/usr/bin/env python3
"""Check native Fabric Debugger data against the frozen CPU firmware."""
import argparse
from collections import Counter
import csv
import datetime
import hashlib
import json
from pathlib import Path
import re

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter
from vcdvcd import VCDVCD

FLAGS = ("ifid_valid", "idex_valid", "exmem_valid", "memwb_valid",
         "load_use_stall", "ex_mispredict", "ex_branch_taken", "take_trap")


def sha256(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def instructions(path):
    result, function = {}, None
    for line in path.read_text().splitlines():
        label = re.fullmatch(r"([0-9a-f]+) <([^>]+)>:", line)
        if label:
            function = label[2]
        decoded = re.match(r"\s*([0-9a-f]+):\s+([0-9a-f]{8})\s+(.+)", line)
        if decoded:
            result[int(decoded[1], 16)] = {"word": int(decoded[2], 16),
                                         "assembly": decoded[3].strip(), "function": function}
    if not result:
        raise ValueError("No RV32 instructions in the disassembly")
    return result


def source_registers(word):
    opcode, function = word & 0x7f, word >> 12 & 7
    registers = []
    if opcode in (0x03, 0x13, 0x23, 0x33, 0x63, 0x67) or opcode == 0x73 and function in (1, 2, 3):
        registers.append(word >> 15 & 31)
    if opcode in (0x23, 0x33, 0x63):
        registers.append(word >> 20 & 31)
    return sorted(set(registers) - {0})


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--capture", type=Path, required=True)
    parser.add_argument("--disassembly", type=Path, required=True)
    parser.add_argument("--elf", type=Path, required=True)
    parser.add_argument("--output", type=Path)
    parser.add_argument("--no-update-capture", action="store_true",
                        help="Keep the original capture record unchanged")
    args = parser.parse_args()
    project = args.capture.parent
    output = args.output or args.capture / "analysis"
    if not args.no_update_capture and not output.resolve().is_relative_to(args.capture.resolve()):
        parser.error("Output outside the capture directory requires --no-update-capture")
    output.mkdir(parents=True, exist_ok=True)
    manifest = json.loads((project / "manifest.json").read_text(encoding="utf-8-sig"))
    evidence_path = args.capture / "capture.json"
    evidence = json.loads(evidence_path.read_text(encoding="utf-8-sig"))
    bitstream = project / "generate_bitstream/pg2l200h_mini_coremark_top.sbit"
    if (not manifest["timing_met"] or not evidence["volatile_jtag"] or evidence["flash_written"]
            or sha256(bitstream) != evidence["bitstream_sha256"].lower()
            or evidence["bitstream_sha256"] != manifest["bitstream_sha256"]
            or sha256(args.elf) != manifest["firmware"]["elf_sha256"]):
        raise ValueError("ILA capture, frozen bitstream and firmware do not match")
    for record in evidence["files"]:
        if sha256(args.capture / record["name"]) != record["sha256"].lower():
            raise ValueError(f"ILA data hash differs: {record['name']}")
    vcd_path = args.capture / "cpu_pipeline.vcd"
    text = vcd_path.read_text(encoding="ascii")
    # PDS adds a nonstandard '#Generated' preamble before the VCD header.
    if text.startswith("#Generated by Fabric Debugger"):
        text = text.split("\n", 1)[1]
    waveform = VCDVCD(vcd_string=text)
    expected = {f"fabric_debugger.soc/core/{name}[{bit}]"
                for name in ("ifid_pc", "idex_pc") for bit in range(32)}
    expected.update(f"fabric_debugger.soc/core/{name}" for name in FLAGS)
    if set(waveform.signals) != expected or waveform.endtime != manifest["ila"]["depth"] - 1:
        raise ValueError("Unexpected ILA channels or sample count")
    decoded = instructions(args.disassembly)
    samples = []
    for cycle in range(manifest["ila"]["depth"]):
        def value(name):
            bits = waveform[f"fabric_debugger.soc/core/{name}"][cycle]
            if bits not in ("0", "1"):
                raise ValueError(f"Unknown ILA sample at cycle {cycle}: {name}")
            return int(bits)
        row = {"sample": cycle}
        for name in ("ifid_pc", "idex_pc"):
            row[name] = sum(value(f"{name}[{bit}]") << bit for bit in range(32))
        row.update({name: value(name) for name in FLAGS})
        for name, valid in (("ifid_pc", "ifid_valid"), ("idex_pc", "idex_valid")):
            if row[valid] and (row[name] & 3 or row[name] not in decoded):
                raise ValueError(f"Valid pipeline PC is absent from firmware: {row}")
        row["assembly"] = decoded.get(row["idex_pc"], {}).get("assembly", "")
        row["function"] = decoded.get(row["idex_pc"], {}).get("function", "")
        samples.append(row)
    trigger = evidence["trigger_pc"]
    position = manifest["ila"]["pretrigger_samples"]
    if samples[position]["idex_pc"] != trigger or not samples[position]["idex_valid"]:
        raise ValueError("The configured firmware trigger does not occur at its sample position")
    stalls, redirects, loops = [], [], []
    functions, pcs = Counter(), Counter()
    for index, row in enumerate(samples):
        if row["idex_valid"]:
            functions[row["function"]] += 1
            pcs[row["idex_pc"]] += 1
        if row["load_use_stall"]:
            instruction = decoded[row["idex_pc"]]["word"]
            is_load = instruction & 0x7f == 3
            is_high_mul = instruction & 0x7f == 0x33 and instruction >> 25 == 1 and (instruction >> 12 & 7) in (1, 2, 3)
            if not row["idex_valid"] or not row["ifid_valid"] or not (is_load or is_high_mul):
                raise ValueError(f"Dependency stall has no valid producer: {row}")
            destination = instruction >> 7 & 31
            sources = source_registers(decoded[row["ifid_pc"]]["word"])
            if not destination or destination not in sources:
                raise ValueError(f"Dependency stall has no matching source register: {row}")
            if index + 1 < len(samples):
                following = samples[index + 1]
                if following["idex_valid"]:
                    raise ValueError("Dependency stall did not insert an EX bubble")
                if not following["ifid_valid"] or following["ifid_pc"] != row["ifid_pc"]:
                    raise ValueError("Dependency stall did not hold the decoded instruction")
            stalls.append({"sample": index, "producer_pc": row["idex_pc"],
                           "producer": row["assembly"], "consumer_pc": row["ifid_pc"],
                           "consumer": decoded[row["ifid_pc"]]["assembly"],
                           "destination_register": destination, "source_registers": sources})
        if row["ex_mispredict"]:
            if not row["idex_valid"]:
                raise ValueError("Redirect asserted without a valid EX instruction")
            if index + 1 < len(samples) and (samples[index + 1]["ifid_valid"] or samples[index + 1]["idex_valid"]):
                raise ValueError("Prediction redirect did not flush both younger stages")
            redirects.append({"sample": index, "pc": row["idex_pc"], "assembly": row["assembly"]})
        if row["idex_valid"] and index + 1 < len(samples):
            following = next((sample for sample in samples[index + 1:index + 5] if sample["idex_valid"]), None)
            opcode = decoded[row["idex_pc"]]["word"] & 0x7f
            if following and opcode in (0x63, 0x6f) and following["idex_pc"] < row["idex_pc"]:
                loops.append({"sample": index, "source_pc": row["idex_pc"],
                              "target_pc": following["idex_pc"], "function": row["function"],
                              "assembly": row["assembly"], "mispredicted": bool(row["ex_mispredict"])})
    if not stalls or not redirects or not loops or sum(row["take_trap"] for row in samples):
        raise ValueError("The capture lacks expected CoreMark activity or contains a trap")
    with (output / "samples.csv").open("w", newline="", encoding="ascii") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(samples[0]))
        writer.writeheader()
        writer.writerows(samples)
    loop_counts = Counter((row["source_pc"], row["target_pc"], row["function"]) for row in loops)
    report = {"verified_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(),
              "execution": evidence["execution"], "project": manifest["project"],
              "bitstream_sha256": sha256(bitstream), "vcd_sha256": sha256(vcd_path),
              "firmware_elf_sha256": sha256(args.elf), "disassembly_sha256": sha256(args.disassembly),
              "samples": len(samples), "clock_hz": manifest["clock_hz"],
              "capture_duration_us": len(samples) * 1e6 / manifest["clock_hz"],
              "vendor_vcd_tick_seconds": float(waveform.timescale["timescale"]),
              "time_axis": "Native VCD ticks are sample indexes; physical duration uses the configured CPU clock",
              "trigger": {"pc": trigger, "sample": position, "assembly": decoded[trigger]["assembly"],
                          "function": decoded[trigger]["function"]},
              "asserted_samples": {name: sum(row[name] for row in samples) for name in FLAGS},
              "stall_bubbles_verified": True, "stall_dependencies_verified": True,
              "stall_decode_holds_verified": True, "redirect_flushes_verified": True,
              "function_ex_samples": dict(functions.most_common()),
              "hot_pcs": [{"pc": pc, "ex_samples": count, **decoded[pc]} for pc, count in pcs.most_common(20)],
              "backward_edges": [{"source_pc": source, "target_pc": target, "function": function, "count": count}
                                 for (source, target, function), count in loop_counts.most_common()],
              "stalls": stalls, "redirects": redirects, "loop_events": loops,
              "scope": "One actual 2048-cycle CoreMark sample window; stage occupancy is not a whole-run CPI or predictor accuracy",
              "waveform_content_verified": True}
    report_path = output / "report.json"
    report_path.write_text(json.dumps(report, indent=2) + "\n", encoding="ascii")
    left = position - 12
    right = min(len(samples), position + 164)
    selected = samples[left:right]
    figure, axes = plt.subplots(3, 1, figsize=(15, 8), sharex=True,
                                gridspec_kw={"height_ratios": [2, 2, 3]})
    x = [row["sample"] for row in selected]
    for axis, name, color in zip(axes[:2], ("ifid_pc", "idex_pc"), ("#176a72", "#a8354c")):
        axis.step(x, [row[name] for row in selected], where="post", color=color, linewidth=1)
        axis.set_ylabel(name)
        axis.yaxis.set_major_formatter(FuncFormatter(lambda value, _: f"0x{int(value):x}"))
    for offset, name in enumerate(FLAGS):
        axes[2].step(x, [offset * 1.6 + row[name] for row in selected], where="post", linewidth=1.1)
    axes[2].set_yticks([offset * 1.6 + 0.5 for offset in range(len(FLAGS))], FLAGS)
    axes[2].set_xlabel("Captured CPU sample (one sample per clock)")
    for axis in axes:
        axis.axvline(position, color="#333333", linestyle="--", linewidth=0.8)
        axis.grid(alpha=0.2)
    figure.suptitle(f"Actual JTAG ILA: CoreMark list mergesort, {manifest['clock_hz'] / 1e6:g} MHz")
    figure.tight_layout()
    figure.savefig(output / "pipeline_window.png", dpi=150)
    plt.close(figure)
    summary = ["# Actual CoreMark Pipeline Capture", "",
               f"Project: `{manifest['project']}`. All {len(samples)} samples came from Fabric Debugger JTAG readback.", "",
               f"Trigger: sample {position}, PC `0x{trigger:08x}`, `{decoded[trigger]['function']}`.",
               f"CPU: {manifest['clock_hz'] / 1e6:g} MHz; capture: {report['capture_duration_us']:.3f} us.",
               "Native VCD uses 100 ns placeholder ticks. Analyze sample indexes; do not use them as physical time.", "",
               "| Signal | Asserted samples |", "| --- | ---: |"]
    summary.extend(f"| `{name}` | {report['asserted_samples'][name]} |" for name in FLAGS)
    summary.extend(["", "Every dependency pause has a matching nonzero source/destination register, holds ID and inserts an EX bubble.",
                    "Every prediction redirect flushes both younger stages. No trap was observed.", "",
                    "| Backward edge | Function | Observations |", "| --- | --- | ---: |"])
    summary.extend(f"| `0x{source:x} -> 0x{target:x}` | `{function}` | {count} |"
                   for (source, target, function), count in loop_counts.most_common(12))
    summary.extend(["", "The window includes initialization and predictor training. Counts describe this window only.",
                    "See `samples.csv`, `report.json`, `pipeline_window.png`, and the original WDF/VCD for review.", ""])
    (output / "README.md").write_text("\n".join(summary), encoding="ascii")
    if not args.no_update_capture:
        evidence["waveform_content_verified"] = True
        evidence["analysis"] = {"report": report_path.resolve().relative_to(args.capture.resolve()).as_posix(),
                                "sha256": sha256(report_path), "vcd_sha256": sha256(vcd_path)}
        evidence_path.write_text(json.dumps(evidence, indent=2) + "\n", encoding="ascii")
    print(f"PASS actual ILA: samples={len(samples)}, stalls={len(stalls)}, redirects={len(redirects)}, backward_edges={len(loops)}")


if __name__ == "__main__":
    main()
